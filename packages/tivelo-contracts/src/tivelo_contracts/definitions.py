"""Content-locked research definitions; trust classification is explicit."""

from __future__ import annotations

import re
from typing import Literal, Self

from pydantic import Field, field_validator, model_validator

from .base import Contract, Digest, Key, RelativePath, fingerprint
from .execution import DefinitionReference

MAX_DEFINITION_MANIFEST_BYTES = 1_048_576


class DefinitionFile(Contract):
    path: RelativePath
    sha256: Digest
    size_bytes: int = Field(strict=True, ge=0)

    @field_validator("path")
    @classmethod
    def portable_path(cls, value):
        reserved = {
            "con",
            "prn",
            "aux",
            "nul",
            *(f"com{i}" for i in range(1, 10)),
            *(f"lpt{i}" for i in range(1, 10)),
        }
        for part in value.split("/"):
            if (
                part.endswith((".", " "))
                or part.split(".", 1)[0].casefold() in reserved
                or any(char in part for char in '<>"|?*')
                or any(ord(char) < 32 for char in part)
                or part.casefold() == "__pycache__"
            ):
                raise ValueError("definition file path is not portable")
        if value.casefold() == "definition.json" or value.casefold().endswith((".pyc", ".pyo")):
            raise ValueError("generated bytecode and the definition marker are not source files")
        return value


class DefinitionContents(Contract):
    definition_id: Key
    version: Key
    kind: Literal["strategy", "factor", "signal", "indicator"]
    language: Literal["trusted_python", "controlled_daily_v1"] = "trusted_python"
    entrypoint: str = Field(strict=True, min_length=1, max_length=1024)
    files: tuple[DefinitionFile, ...] = Field(min_length=1, max_length=4096)
    dependencies: tuple[DefinitionReference, ...] = ()
    requirements: tuple[Key, ...] = ()

    @model_validator(mode="after")
    def coherent(self) -> Self:
        names = [file.path for file in self.files]
        if names != sorted(set(names)) or len({name.casefold() for name in names}) != len(names):
            raise ValueError("definition file paths must be unique, portable and sorted")
        folded = {name.casefold() for name in names}
        for name in names:
            parts = name.casefold().split("/")
            for index in range(1, len(parts)):
                parent = "/".join(parts[:index])
                if parent in folded or parent + ".py" in folded:
                    raise ValueError("definition file and package paths conflict")
        if self.language == "trusted_python":
            if not re.fullmatch(
                r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*:[A-Za-z_][A-Za-z0-9_]*",
                self.entrypoint,
            ):
                raise ValueError("invalid Python entrypoint")
            module = self.entrypoint.split(":")[0]
            if "__init__" in module.split("."):
                raise ValueError("entrypoints name packages, not __init__ modules")
            path = module.replace(".", "/")
            if sum(name in names for name in (path + ".py", path + "/__init__.py")) != 1:
                raise ValueError("entrypoint must identify exactly one declared Python module")
        elif (
            self.kind != "strategy"
            or names != [self.entrypoint]
            or not self.entrypoint.endswith(".json")
            or self.dependencies
            or self.requirements
        ):
            raise ValueError("controlled daily v1 declares one JSON strategy and no code dependencies")
        ids = [ref.definition_id for ref in self.dependencies]
        if ids != sorted(set(ids)) or self.definition_id in ids:
            raise ValueError("direct dependencies must be unique, sorted and not self-references")
        if self.requirements != tuple(sorted(set(self.requirements))):
            raise ValueError("runtime requirements must be unique and sorted")
        return self


class DefinitionBundle(Contract):
    format: Literal["tivelo-research-definition"] = "tivelo-research-definition"
    format_version: Literal["1.0"] = "1.0"
    bundle_id: Digest
    contents: DefinitionContents

    @model_validator(mode="after")
    def verify_hash(self) -> Self:
        if self.bundle_id != fingerprint(self.contents):
            raise ValueError("definition content fingerprint mismatch")
        return self

    @classmethod
    def create(cls, contents: DefinitionContents) -> Self:
        return cls(bundle_id=fingerprint(contents), contents=contents)

    def reference(self, parameters_json: str = "{}") -> DefinitionReference:
        return DefinitionReference(
            definition_id=self.contents.definition_id,
            version=self.contents.version,
            sha256=self.bundle_id,
            parameters_json=parameters_json,
        )
